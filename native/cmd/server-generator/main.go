// server-generator — генератор конфигов СЕРВЕРНОЙ стороны (Hysteria 2 / TUIC)
// и самоподписанных TLS-сертификатов для тестовых развёртываний.
//
// Примеры:
//
//	server-generator -protocol hy2 -password secret -obfs-password obfs123 -out server.yaml
//	server-generator -protocol tuic -uuid 00000000-0000-0000-0000-000000000001 -password p -out tuic.toml
//	server-generator -gen-cert ./certs -cert-domain vpn.example.com
package main

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"flag"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"text/template"
	"time"
)

type hy2Config struct {
	Listen       string
	Auth         string
	Cert         string
	Key          string
	ACMEDomains  []string
	ACMEEmail    string
	ObfsType     string
	ObfsPassword string
	Up           string
	Down         string
}

type tuicConfig struct {
	Addr       string
	UUID       string
	Password   string
	Cert       string
	Key        string
	Congestion string
	ALPN       []string
}

const hy2Template = `# Hysteria 2 server configuration
# Generated by FLICKER VPN Pro server-generator
listen: {{.Listen}}

{{if .ACMEDomains}}acme:
  domains:
{{range .ACMEDomains}}    - {{.}}
{{end}}  email: {{.ACMEEmail}}
{{else}}tls:
  cert: {{.Cert}}
  key: {{.Key}}
{{end}}
auth:
  type: password
  password: {{.Auth}}
{{if .ObfsType}}
obfs:
  type: {{.ObfsType}}
  password: {{.ObfsPassword}}
{{end}}
bandwidth:
  up: {{.Up}}
  down: {{.Down}}

masquerade:
  type: proxy
  proxy:
    url: https://cloudflare.com
    rewriteHost: true
`

const tuicTemplate = `# TUIC v5 server configuration (tuic-server)
# Generated by FLICKER VPN Pro server-generator
[server]
addr = "{{.Addr}}"
max_connections = 1024

[users]
"{{.UUID}}" = "{{.Password}}"

[cert]
certificate = "{{.Cert}}"
private_key = "{{.Key}}"

[network]
congestion_control = "{{.Congestion}}"
alpn = [{{range $i, $a := .ALPN}}{{if $i}}, {{end}}"{{$a}}"{{end}}]
max_idle_timeout = "10s"
max_udp_relay_payload_size = 1500
`

func generate(path, tmplText string, data any) error {
	tmpl, err := template.New(filepath.Base(path)).Parse(tmplText)
	if err != nil {
		return err
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return tmpl.Execute(f, data)
}

// genCert пишет самоподписанный ECDSA P-256 сертификат + ключ.
func genCert(dir, domain string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	serial, _ := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	tmplCert := x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: domain, Organization: []string{"FLICKER VPN Test"}},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(365 * 24 * time.Hour),
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageCertSign,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		IsCA:                  true,
		DNSNames:              []string{domain},
		IPAddresses:           []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("::1")},
	}
	der, err := x509.CreateCertificate(rand.Reader, &tmplCert, &tmplCert, &key.PublicKey, key)
	if err != nil {
		return err
	}
	certPath := filepath.Join(dir, "cert.pem")
	keyPath := filepath.Join(dir, "key.pem")
	cf, err := os.Create(certPath)
	if err != nil {
		return err
	}
	if err := pem.Encode(cf, &pem.Block{Type: "CERTIFICATE", Bytes: der}); err != nil {
		cf.Close()
		return err
	}
	cf.Close()
	kb, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		return err
	}
	kf, err := os.Create(keyPath)
	if err != nil {
		return err
	}
	if err := pem.Encode(kf, &pem.Block{Type: "EC PRIVATE KEY", Bytes: kb}); err != nil {
		kf.Close()
		return err
	}
	kf.Close()
	fmt.Printf("✅ Сертификат: %s\n✅ Ключ: %s\n", certPath, keyPath)
	return nil
}

func main() {
	protocol := flag.String("protocol", "hy2", "hy2 | tuic")
	out := flag.String("out", "", "выходной файл конфига")
	listen := flag.String("listen", ":443", "адрес прослушивания")
	password := flag.String("password", "CHANGE_ME", "пароль (hy2) / пароль пользователя (tuic)")
	uuid := flag.String("uuid", "00000000-0000-0000-0000-000000000000", "UUID пользователя (tuic)")
	obfsType := flag.String("obfs", "salamander", "тип обфускации hy2 (salamander | пусто)")
	obfsPassword := flag.String("obfs-password", "CHANGE_ME_OBFS", "пароль обфускации")
	cert := flag.String("cert", "/etc/flicker/cert.pem", "путь к сертификату")
	key := flag.String("key", "/etc/flicker/key.pem", "путь к ключу")
	domains := flag.String("domains", "", "ACME-домены через запятую (hy2, вместо cert/key)")
	email := flag.String("email", "admin@example.com", "ACME email")
	up := flag.String("up", "100 mbps", "апстрим")
	down := flag.String("down", "200 mbps", "даунстрим")
	congestion := flag.String("congestion", "bbr", "congestion control (tuic)")
	genCertDir := flag.String("gen-cert", "", "сгенерировать самоподписанный сертификат в каталог")
	certDomain := flag.String("cert-domain", "flicker.local", "CN/SAN сертификата")
	flag.Parse()

	if *genCertDir != "" {
		if err := genCert(*genCertDir, *certDomain); err != nil {
			fmt.Fprintln(os.Stderr, "Ошибка:", err)
			os.Exit(1)
		}
		if *out == "" {
			return
		}
	}

	if *out == "" {
		fmt.Fprintln(os.Stderr, "Использование: server-generator -protocol hy2|tuic -out FILE [-gen-cert DIR]")
		flag.Usage()
		os.Exit(1)
	}

	switch *protocol {
	case "hy2":
		cfg := hy2Config{
			Listen:       *listen,
			Auth:         *password,
			Cert:         *cert,
			Key:          *key,
			ACMEEmail:    *email,
			ObfsType:     *obfsType,
			ObfsPassword: *obfsPassword,
			Up:           *up,
			Down:         *down,
		}
		if *domains != "" {
			for _, d := range splitCSV(*domains) {
				cfg.ACMEDomains = append(cfg.ACMEDomains, d)
			}
		}
		if err := generate(*out, hy2Template, cfg); err != nil {
			fmt.Fprintln(os.Stderr, "Ошибка:", err)
			os.Exit(1)
		}
	case "tuic":
		cfg := tuicConfig{
			Addr:       *listen,
			UUID:       *uuid,
			Password:   *password,
			Cert:       *cert,
			Key:        *key,
			Congestion: *congestion,
			ALPN:       []string{"h3", "h2"},
		}
		if err := generate(*out, tuicTemplate, cfg); err != nil {
			fmt.Fprintln(os.Stderr, "Ошибка:", err)
			os.Exit(1)
		}
	default:
		fmt.Fprintf(os.Stderr, "Неизвестный протокол: %s\n", *protocol)
		os.Exit(1)
	}
	fmt.Printf("✅ Конфиг %s: %s\n", *protocol, *out)
}

func splitCSV(s string) []string {
	var out []string
	cur := ""
	for _, r := range s {
		if r == ',' {
			if cur != "" {
				out = append(out, cur)
			}
			cur = ""
			continue
		}
		if r == ' ' && cur == "" {
			continue
		}
		cur += string(r)
	}
	if cur != "" {
		out = append(out, cur)
	}
	return out
}
